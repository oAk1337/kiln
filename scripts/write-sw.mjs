import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const dist = path.resolve("dist");
const files = walk(dist)
  .map((file) => file.split(path.sep).join("/"))
  .filter((file) => file !== "sw.js")
  .sort();

const hash = createHash("sha256");
for (const file of files) hash.update(fs.readFileSync(path.join(dist, file)));
const version = hash.digest("hex").slice(0, 12);
const assets = files.map((file) => `./${file}`);

const source = `/* Kiln service worker. Cache kiln-${version}. Generated by scripts/write-sw.mjs. */
const CACHE = ${JSON.stringify(`kiln-${version}`)};
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.endsWith("/sw.js")) return;

  if (request.mode === "navigate") {
    event.respondWith(cacheFirstNavigation(request));
    return;
  }
  event.respondWith(cacheFirst(request));
});

async function cacheFirstNavigation(request) {
  const cache = await caches.open(CACHE);
  const indexUrl = new URL("./index.html", self.registration.scope).href;
  const cached = await cache.match(request, { ignoreSearch: true })
    || await cache.match(indexUrl, { ignoreSearch: true })
    || await cache.match("./index.html", { ignoreSearch: true });
  if (cached) return cached;
  try {
    const fresh = await fetch(request);
    if (fresh.ok) cache.put(request, fresh.clone());
    return fresh;
  } catch {
    return cached || new Response("Offline", { status: 503, headers: { "Content-Type": "text/plain" } });
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(request, { ignoreSearch: true });
  if (cached) return cached;
  const fresh = await fetch(request);
  if (fresh.ok) cache.put(request, fresh.clone());
  return fresh;
}
`;

fs.writeFileSync(path.join(dist, "sw.js"), source);
console.log(`wrote dist/sw.js kiln-${version} (${assets.length} assets)`);

function walk(dir, base = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(abs, base));
    else out.push(path.relative(base, abs));
  }
  return out;
}
